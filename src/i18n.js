let language = detectLanguage();
let userSelected = localStorage.getItem('yolo-viewer-lang') === 'en'
  || localStorage.getItem('yolo-viewer-lang') === 'zh';
const subscribers = new Set();

function detectLanguage() {
  const saved = localStorage.getItem('yolo-viewer-lang');
  if (saved === 'en' || saved === 'zh') return saved;
  const system = (navigator.language || 'en').toLowerCase();
  return system.startsWith('zh') ? 'zh' : 'en';
}

export function t(key, params = {}) {
  let text = messages[language][key] ?? messages.en[key] ?? key;
  for (const [name, value] of Object.entries(params)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function getLanguage() {
  return language;
}

export function setLanguage(next, { persist = true } = {}) {
  if (next !== 'en' && next !== 'zh') return;
  language = next;
  if (persist) {
    userSelected = true;
    localStorage.setItem('yolo-viewer-lang', next);
  }
  applyAll();
}

export function toggleLanguage() {
  setLanguage(language === 'zh' ? 'en' : 'zh');
}

export function onLanguageChange(callback) {
  subscribers.add(callback);
}

function applyStatic() {
  for (const [id, key, attr] of staticBindings) {
    const element = document.getElementById(id);
    if (!element) continue;
    if (attr === 'textContent') element.textContent = t(key);
    else element.setAttribute(attr, t(key));
  }
  const langButton = document.getElementById('btn-lang');
  if (langButton) langButton.textContent = t('langButton');
}

function applyAll() {
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  document.title = t('brandTitle');
  applyStatic();
  subscribers.forEach((callback) => callback());
}

export async function initI18n() {
  applyAll();
  if (userSelected) return;
  try {
    const systemLocale = await invoke('system_locale');
    if (!systemLocale) return;
    const detected = String(systemLocale).toLowerCase().startsWith('zh') ? 'zh' : 'en';
    if (detected !== language) {
      language = detected;
      applyAll();
    }
  } catch { /* system locale unavailable */ }
}

export function localeNumber(value) {
  return Number(value || 0).toLocaleString(language === 'zh' ? 'zh-CN' : 'en-US');
}
